/// Workspace detail console: identity, storage and members (Overview),
/// workspace-scoped mail administration (Mail), and Flywheel app usage.
///
/// Reached from the workspace list by slug. The route itself is generated by
/// auto_route from [WorkspaceDetailPage] (`WorkspaceDetailRoute`).
@RoutePage()
class WorkspaceDetailPage extends ConsumerStatefulWidget {
  const WorkspaceDetailPage({super.key, @PathParam('slug') required this.slug});

  final String slug;

  @override
  ConsumerState<WorkspaceDetailPage> createState() => _WorkspaceDetailPageState();
}

class _WorkspaceDetailPageState extends ConsumerState<WorkspaceDetailPage> {
  void _refresh() {
    ref.invalidate(workspacesProvider);
    ref.invalidate(selectedWorkspaceProvider);
  }

  @override
  Widget build(BuildContext context) {
    final workspaces = ref.watch(workspacesProvider);
    final workspace = _workspaceBySlug(
      workspaces.value ?? const <Workspace>[],
      widget.slug,
    );

    return DefaultTabController(
      length: 3,
      child: PageScaffold(
        title: workspace?.name ?? 'workspace'.tr(),
        subtitle: workspace == null ? null : '@${workspace.slug}',
        action: IconButton.filledTonal(
          tooltip: 'refresh'.tr(),
          onPressed: _refresh,
          icon: const Icon(Symbols.refresh),
        ),
        bottom: TabBar(
          tabs: [
            Tab(text: 'workspaceOverview'.tr()),
            Tab(text: 'mail'.tr()),
            Tab(text: 'flywheel'.tr()),
          ],
        ),
        child: workspaces.when(
          loading: () => const PageLoading(),
          error: (error, _) => PageError(
            message: 'workspaceLoadError'.tr(),
            onRetry: _refresh,
          ),
          data: (items) {
            final value = _workspaceBySlug(items, widget.slug);
            if (value == null) {
              return EmptyState(
                icon: Symbols.workspaces,
                title: 'workspaceNotFound'.tr(),
              );
            }
            return TabBarView(
              children: [
                _OverviewTab(workspace: value),
                _MailTab(workspace: value),
                _FlywheelTab(workspace: value),
              ],
            );
          },
        ),
      ),
    );
  }
}

