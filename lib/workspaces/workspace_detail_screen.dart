class _UsageMeter extends StatelessWidget {
  const _UsageMeter({
    required this.label,
    required this.used,
    required this.limit,
    this.remaining,
    this.isBytes = false,
  });

  final String label;
  final int used;
  final int limit;
  final int? remaining;
  final bool isBytes;

  String _format(int value) => isBytes ? _formatBytes(value) : '$value';

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final text = Theme.of(context).textTheme;
    final hasLimit = limit > 0;
    final ratio = hasLimit ? (used / limit).clamp(0.0, 1.0) : 0.0;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          children: [
            Expanded(
              child: Text(
                label,
                style: text.titleSmall?.copyWith(fontWeight: FontWeight.w600),
              ),
            ),
            const SizedBox(width: 12),
            Text(
              hasLimit ? '${_format(used)} / ${_format(limit)}' : _format(used),
              style: text.bodyMedium?.copyWith(fontWeight: FontWeight.w600),
            ),
          ],
        ),
        if (hasLimit) ...[
          const SizedBox(height: 8),
          ClipRRect(
            borderRadius: BorderRadius.circular(6),
            child: LinearProgressIndicator(value: ratio, minHeight: 8),
          ),
        ],
        if (remaining != null) ...[
          const SizedBox(height: 6),
          Text(
            '${'quotaRemaining'.tr()}: '
            '${hasLimit ? _format(remaining!) : 'mailStorageQuotaUnlimited'.tr()}',
            style: text.bodySmall?.copyWith(color: scheme.onSurfaceVariant),
          ),
        ],
      ],
    );
  }
}

