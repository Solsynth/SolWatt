  Widget _storageSection(
    Workspace workspace,
    AsyncValue<WorkspaceStorageQuota?> quota,
  ) {
    final scheme = Theme.of(context).colorScheme;
    final text = Theme.of(context).textTheme;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        Row(
          children: [
            Expanded(
              child: Text(
                'storageQuota'.tr(),
                style: text.titleMedium?.copyWith(fontWeight: FontWeight.w700),
              ),
            ),
          ],
        ),
        const SizedBox(height: 12),
        quota.when(
          loading: () => const Padding(
            padding: EdgeInsets.symmetric(vertical: 24),
            child: Center(child: CircularProgressIndicator()),
          ),
          error: (error, _) => _InlineError(
            message: 'errorLoadingQuota'.tr(),
            onRetry: () =>
                ref.invalidate(workspaceStorageQuotaProvider(workspace.slug)),
          ),
          data: (value) {
            if (value == null) {
              return _InlineError(
                message: 'errorLoadingQuota'.tr(),
                onRetry: () => ref.invalidate(
                  workspaceStorageQuotaProvider(workspace.slug),
                ),
              );
            }
            final hasTotal = value.totalBytes > 0;
            final ratio = hasTotal
                ? (value.usedBytes / value.totalBytes).clamp(0.0, 1.0)
                : 0.0;
            return Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  'storageUsed'.tr(
                    namedArgs: {
                      'used': _formatBytes(value.usedBytes),
                      'total': _formatBytes(value.totalBytes),
                      'percent': (ratio * 100).toStringAsFixed(0),
                    },
                  ),
                ),
                if (hasTotal) ...[
                  const SizedBox(height: 8),
                  ClipRRect(
                    borderRadius: BorderRadius.circular(6),
                    child: LinearProgressIndicator(value: ratio, minHeight: 8),
                  ),
                ],
                const SizedBox(height: 8),
                Text(
                  'fileCount'.tr(
                    namedArgs: {'count': '${value.totalFileCount}'},
                  ),
                  style: text.bodySmall?.copyWith(
                    color: scheme.onSurfaceVariant,
                  ),
                ),
                if (value.services.isNotEmpty) ...[
                  const SizedBox(height: 16),
                  Text(
                    'serviceUsage'.tr(),
                    style: text.titleSmall?.copyWith(
                      fontWeight: FontWeight.w700,
                    ),
                  ),
                  const SizedBox(height: 8),
                  for (final service in value.services)
                    Padding(
                      padding: const EdgeInsets.symmetric(vertical: 4),
                      child: Row(
                        children: [
                          Expanded(
                            child: Text(
                              service.displayName,
                              maxLines: 1,
                              overflow: TextOverflow.ellipsis,
                              style: const TextStyle(
                                fontWeight: FontWeight.w600,
                              ),
                            ),
                          ),
                          const SizedBox(width: 12),
                          Text(
                            _formatBytes(service.usedBytes),
                            style: text.bodyMedium?.copyWith(
                              color: scheme.onSurfaceVariant,
                            ),
                          ),
                        ],
                      ),
                    ),
                ],
                if (value.calculatedAt != null) ...[
                  const SizedBox(height: 12),
                  Text(
                    'quotaCalculatedAt'.tr(
                      args: [_formatDateTime(value.calculatedAt!)],
                    ),
                    style: text.bodySmall?.copyWith(
                      color: scheme.onSurfaceVariant,
                    ),
                  ),
                ],
              ],
            );
          },
        ),
      ],
    );
  }

  Widget _membersSection(Workspace workspace) => FutureBuilder<List<WorkspaceMember>>(
    future: _members,
    builder: (context, snapshot) {
      if (snapshot.connectionState != ConnectionState.done) {
        return const Padding(
          padding: EdgeInsets.symmetric(vertical: 16),
          child: Center(child: CircularProgressIndicator()),
        );
      }
      if (snapshot.hasError) {
        return _InlineError(
          message: 'couldNotLoadMembers'.tr(),
          onRetry: () => setState(_reloadMembers),
        );
      }
      final members = snapshot.data ?? const <WorkspaceMember>[];
      if (members.isEmpty) {
        return _InlineEmpty(
          icon: Symbols.group,
          message: 'noMembers'.tr(),
          description: 'noWorkspaceMembersAvailable'.tr(),
        );
      }
      return Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            'workspaceMemberCount'.tr(
              namedArgs: {'count': '${members.length}'},
            ),
            style: Theme.of(context).textTheme.bodySmall?.copyWith(
              color: Theme.of(context).colorScheme.onSurfaceVariant,
            ),
          ),
          const SizedBox(height: 12),
          Wrap(
            spacing: 8,
            runSpacing: 8,
            children: [
              for (final member in members.take(5))
                _MemberChip(member: member),
              if (members.length > 5)
                Padding(
                  padding: const EdgeInsets.symmetric(vertical: 8),
                  child: Text(
                    '+${members.length - 5}',
                    style: Theme.of(context).textTheme.labelLarge,
                  ),
                ),
            ],
          ),
        ],
      );
    },
  );
}

