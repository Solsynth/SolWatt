class _MailData {
  const _MailData({
    required this.mailHost,
    required this.mailboxes,
    required this.mailboxUsage,
    required this.domains,
    required this.credentials,
  });

  final String mailHost;
  final List<MailMailbox> mailboxes;
  final MailUsageSummary mailboxUsage;
  final List<MailCustomDomain> domains;
  final List<MailCredential> credentials;
}

typedef _MailboxDraft = ({String address, String? name, bool isDefault});

class _MailTab extends ConsumerStatefulWidget {
  const _MailTab({required this.workspace});

  final Workspace workspace;

  @override
  ConsumerState<_MailTab> createState() => _MailTabState();
}

class _MailTabState extends ConsumerState<_MailTab> {
  late Future<_MailData> _data;

  @override
  void initState() {
    super.initState();
    _data = _load();
  }

  Future<_MailData> _load() async {
    final client = ref.read(wattEngineClientProvider);
    final workspaceId = widget.workspace.id;
    var mailHost = '';
    try {
      mailHost = await client.getMailHost();
    } catch (_) {
      // A missing host only affects address rendering; the rest still loads.
    }
    final results = await Future.wait<Object>([
      client.listMailboxes(workspaceId: workspaceId),
      client.getWorkspaceMailboxUsage(workspaceId),
      client.listCustomDomains(workspaceId: workspaceId),
      client.listMailCredentials(),
    ]);
    return _MailData(
      mailHost: mailHost,
      mailboxes: results[0] as List<MailMailbox>,
      mailboxUsage: results[1] as MailUsageSummary,
      domains: results[2] as List<MailCustomDomain>,
      credentials: results[3] as List<MailCredential>,
    );
  }

  void _reload() {
    if (!mounted) return;
    setState(() => _data = _load());
  }

  Future<void> _createMailbox(_MailData data) async {
    final draft = await showModalBottomSheet<_MailboxDraft>(
      context: context,
      useRootNavigator: true,
      isScrollControlled: true,
      builder: (_) => _CreateMailboxSheet(mailHost: data.mailHost),
    );
    if (draft == null || !mounted) return;
    try {
      await ref
          .read(wattEngineClientProvider)
          .createMailbox(
            address: draft.address,
            workspaceId: widget.workspace.id,
            name: draft.name,
            isDefault: draft.isDefault,
          );
      _reload();
      showSnackBar('mailboxCreated'.tr());
    } catch (error) {
      showSnackBar(wattApiErrorMessage(error));
    }
  }

  Future<void> _openRouting(_MailData data, MailMailbox mailbox) async {
    await showModalBottomSheet<void>(
      context: context,
      useRootNavigator: true,
      isScrollControlled: true,
      builder: (_) => _MailboxRoutingSheet(
        mailbox: mailbox,
        workspaceId: widget.workspace.id,
        mailHost: data.mailHost,
        domains: data.domains,
        onChanged: _reload,
      ),
    );
  }

  Future<void> _createCredential(_MailData data) async {
    final created = await showModalBottomSheet<MailCredentialCreated>(
      context: context,
      useRootNavigator: true,
      isScrollControlled: true,
      builder: (_) => _CreateCredentialSheet(
        mailboxes: data.mailboxes,
        mailHost: data.mailHost,
      ),
    );
    if (created == null || !mounted) return;
    _reload();
    await _showSecret(created.secret);
  }

  Future<void> _showSecret(String secret) => showModalBottomSheet<void>(
    context: context,
    useRootNavigator: true,
    isScrollControlled: true,
    builder: (_) => _CredentialSecretSheet(secret: secret),
  );

  Future<void> _revokeCredential(MailCredential credential) async {
    final confirmed = await showConfirmAlert(
      'revokeCredentialConfirm'.tr(namedArgs: {'label': credential.label}),
      'revokeCredential'.tr(),
      icon: Symbols.key,
      isDanger: true,
      confirmLabel: 'revoke'.tr(),
    );
    if (!confirmed || !mounted) return;
    try {
      await ref
          .read(wattEngineClientProvider)
          .revokeMailCredential(credential.id);
      _reload();
      showSnackBar('credentialRevoked'.tr());
    } catch (error) {
      showSnackBar(wattApiErrorMessage(error));
    }
  }

  Future<void> _createDomain() async {
    final domain = await showModalBottomSheet<String>(
      context: context,
      useRootNavigator: true,
      isScrollControlled: true,
      builder: (_) => const _CreateDomainSheet(),
    );
    if (domain == null || domain.isEmpty || !mounted) return;
    try {
      await ref
          .read(wattEngineClientProvider)
          .createCustomDomain(workspaceId: widget.workspace.id, domain: domain);
      _reload();
      showSnackBar('workspaceDomainAdded'.tr());
    } catch (error) {
      showSnackBar(wattApiErrorMessage(error));
    }
  }

  Future<void> _refreshDomain(MailCustomDomain domain) async {
    try {
      await ref.read(wattEngineClientProvider).refreshCustomDomain(domain.id);
      _reload();
      showSnackBar('workspaceDomainRefreshed'.tr());
    } catch (error) {
      showSnackBar(wattApiErrorMessage(error));
    }
  }

  @override
  Widget build(BuildContext context) => FutureBuilder<_MailData>(
    future: _data,
    builder: (context, snapshot) {
      if (snapshot.connectionState != ConnectionState.done) {
        return const PageLoading();
      }
      if (snapshot.hasError) {
        return PageError(
          message: 'workspaceMailLoadError'.tr(),
          onRetry: _reload,
        );
      }
      final data = snapshot.data!;
      final mailboxIds = {for (final mailbox in data.mailboxes) mailbox.id};
      final credentials = data.credentials
          .where((credential) => mailboxIds.contains(credential.mailboxId))
          .toList(growable: false);

      return ListView(
        padding: const EdgeInsets.only(top: 16, bottom: 32),
        children: [
          _TitledPanel(
            title: 'workspaceMailboxes'.tr(),
            trailing: FilledButton.icon(
              onPressed: () => _createMailbox(data),
              icon: const Icon(Symbols.add),
              label: Text('newMailbox'.tr()),
            ),
            child: data.mailboxes.isEmpty
                ? _InlineEmpty(
                    icon: Symbols.mail,
                    message: 'workspaceMailboxesEmpty'.tr(),
                  )
                : Column(
                    children: [
                      for (var i = 0; i < data.mailboxes.length; i++) ...[
                        if (i > 0) const Divider(height: 1),
                        _MailboxTile(
                          mailbox: data.mailboxes[i],
                          mailHost: data.mailHost,
                          onTap: () =>
                              _openRouting(data, data.mailboxes[i]),
                        ),
                      ],
                    ],
                  ),
          ),
          const SizedBox(height: 12),
          _TitledPanel(
            title: 'workspaceMailboxUsage'.tr(),
            child: _UsageMeter(
              label: 'workspaceMailboxes'.tr(),
              used: data.mailboxUsage.used,
              limit: data.mailboxUsage.limit,
              remaining: data.mailboxUsage.remaining,
            ),
          ),
          const SizedBox(height: 12),
          _TitledPanel(
            title: 'mailCredentials'.tr(),
            trailing: FilledButton.tonalIcon(
              onPressed: data.mailboxes.isEmpty
                  ? null
                  : () => _createCredential(data),
              icon: const Icon(Symbols.key),
              label: Text('createCredential'.tr()),
            ),
            child: credentials.isEmpty
                ? _InlineEmpty(
                    icon: Symbols.key,
                    message: 'noCredentials'.tr(),
                    description: 'noCredentialsDescription'.tr(),
                  )
                : Column(
                    children: [
                      for (var i = 0; i < credentials.length; i++) ...[
                        if (i > 0) const Divider(height: 1),
                        _CredentialTile(
                          credential: credentials[i],
                          mailbox: _mailboxById(
                            data.mailboxes,
                            credentials[i].mailboxId,
                          ),
                          mailHost: data.mailHost,
                          onRevoke: () => _revokeCredential(credentials[i]),
                        ),
                      ],
                    ],
                  ),
          ),
          const SizedBox(height: 12),
          _TitledPanel(
            title: 'workspaceCustomDomains'.tr(),
            trailing: FilledButton.tonalIcon(
              onPressed: _createDomain,
              icon: const Icon(Symbols.add),
              label: Text('workspaceAddDomain'.tr()),
            ),
            child: data.domains.isEmpty
                ? _InlineEmpty(
                    icon: Symbols.dns,
                    message: 'workspaceDomainsEmpty'.tr(),
                  )
                : Column(
                    children: [
                      for (final domain in data.domains)
                        _DomainTile(
                          domain: domain,
                          onRefresh: () => _refreshDomain(domain),
                        ),
                    ],
                  ),
          ),
        ],
      );
    },
  );
}

MailMailbox? _mailboxById(List<MailMailbox> mailboxes, String id) {
  for (final mailbox in mailboxes) {
    if (mailbox.id == id) return mailbox;
  }
  return null;
}

class _MailboxTile extends StatelessWidget {
  const _MailboxTile({
    required this.mailbox,
    required this.mailHost,
    required this.onTap,
  });

  final MailMailbox mailbox;
  final String mailHost;
  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final text = Theme.of(context).textTheme;
    final name = mailbox.name?.trim();
    return InkWell(
      onTap: onTap,
