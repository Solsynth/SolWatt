class _FlywheelTab extends ConsumerStatefulWidget {
  const _FlywheelTab({required this.workspace});

  final Workspace workspace;

  @override
  ConsumerState<_FlywheelTab> createState() => _FlywheelTabState();
}

class _FlywheelTabState extends ConsumerState<_FlywheelTab> {
  late Future<List<FlywheelOwnerApp>> _apps;

  @override
  void initState() {
    super.initState();
    _reload();
  }

  void _reload() {
    _apps = ref
        .read(wattEngineClientProvider)
        .listFlywheelApps(widget.workspace.id);
  }

  Future<void> _openApp(FlywheelOwnerApp app) async {
    await showFlywheelApp(
      context,
      workspaceId: widget.workspace.id,
      app: app,
    );
    if (mounted) setState(_reload);
  }

  @override
  Widget build(BuildContext context) => FutureBuilder<List<FlywheelOwnerApp>>(
    future: _apps,
    builder: (context, snapshot) {
      if (snapshot.connectionState != ConnectionState.done) {
        return const PageLoading();
      }
      if (snapshot.hasError) {
        final denied =
            snapshot.error is DioException &&
            (snapshot.error as DioException).response?.statusCode == 403;
        if (denied) {
          return EmptyState(
            icon: Symbols.lock,
            title: 'workspaceFlywheelOwnerOnly'.tr(),
            message: 'workspaceFlywheelOwnerOnlyDescription'.tr(),
          );
        }
        return PageError(
          message: 'workspaceFlywheelLoadError'.tr(),
          onRetry: () => setState(_reload),
        );
      }
      final apps = snapshot.data ?? const <FlywheelOwnerApp>[];
      if (apps.isEmpty) {
        return EmptyState(
          icon: Symbols.sync,
          title: 'workspaceFlywheelEmpty'.tr(),
        );
      }
      return ListView(
        padding: const EdgeInsets.only(top: 16, bottom: 32),
        children: [
          _TitledPanel(
            title: 'flywheel'.tr(),
            child: Column(
              children: [
                for (var i = 0; i < apps.length; i++) ...[
                  if (i > 0) const Divider(height: 1),
                  _FlywheelAppTile(
                    app: apps[i],
                    onTap: () => _openApp(apps[i]),
                  ),
                ],
              ],
            ),
          ),
        ],
      );
    },
  );
}

