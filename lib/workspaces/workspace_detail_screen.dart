  });

  final List<MailAlias> aliases;
  final List<MailForwarding> forwardings;
  final MailboxQuota quota;
  final MailSendUsage sendUsage;
}

class _MailboxRoutingSheet extends ConsumerStatefulWidget {
  const _MailboxRoutingSheet({
    required this.mailbox,
    required this.workspaceId,
    required this.mailHost,
    required this.domains,
    required this.onChanged,
  });

  final MailMailbox mailbox;
  final String workspaceId;
  final String mailHost;
  final List<MailCustomDomain> domains;
  final VoidCallback onChanged;

  @override
  ConsumerState<_MailboxRoutingSheet> createState() =>
      _MailboxRoutingSheetState();
}

class _MailboxRoutingSheetState extends ConsumerState<_MailboxRoutingSheet> {
  final _aliasLocalPart = TextEditingController();
  final _aliasName = TextEditingController();
  final _forwardingDestination = TextEditingController();
  late Future<_RoutingData> _data;
  String? _customDomainId;
  String? _aliasId;
  bool _aliasSaving = false;
  bool _forwardingSaving = false;

  @override
  void initState() {
    super.initState();
    _data = _load();
  }

  @override
  void dispose() {
    _aliasLocalPart.dispose();
    _aliasName.dispose();
    _forwardingDestination.dispose();
    super.dispose();
  }

  Future<_RoutingData> _load() async {
    final client = ref.read(wattEngineClientProvider);
    final mailboxId = widget.mailbox.id;
    final results = await Future.wait<Object>([
      client.listMailboxAliases(mailboxId),
      client.listMailForwardings(mailboxId),
      client.getMailboxQuota(mailboxId),
      client.getWorkspaceSendUsage(widget.workspaceId),
    ]);
    return _RoutingData(
      aliases: results[0] as List<MailAlias>,
      forwardings: results[1] as List<MailForwarding>,
      quota: results[2] as MailboxQuota,
      sendUsage: results[3] as MailSendUsage,
    );
  }

  void _reload() {
    if (!mounted) return;
    setState(() => _data = _load());
    widget.onChanged();
  }

  Future<void> _createAlias() async {
    final domainId = _customDomainId;
    final localPart = _aliasLocalPart.text.trim().toLowerCase();
    if (domainId == null || localPart.isEmpty) return;
    setState(() => _aliasSaving = true);
    try {
      await ref
          .read(wattEngineClientProvider)
          .createMailboxAlias(
            mailboxId: widget.mailbox.id,
            customDomainId: domainId,
            localPart: localPart,
            name: _aliasName.text.trim(),
          );
      _aliasLocalPart.clear();
      _aliasName.clear();
      showSnackBar('aliasCreated'.tr());
      _reload();
    } catch (error) {
      showSnackBar(wattApiErrorMessage(error));
    } finally {
      if (mounted) setState(() => _aliasSaving = false);
    }
  }

  Future<void> _deleteAlias(MailAlias alias) async {
    final confirmed = await showConfirmAlert(
      'removeAliasConfirm'.tr(namedArgs: {'address': alias.address}),
      'removeAlias'.tr(),
      icon: Symbols.delete,
      isDanger: true,
      confirmLabel: 'remove'.tr(),
    );
    if (!confirmed) return;
    try {
      await ref
          .read(wattEngineClientProvider)
          .deleteMailboxAlias(widget.mailbox.id, alias.id);
      showSnackBar('aliasRemoved'.tr());
      _reload();
    } catch (error) {
      showSnackBar(wattApiErrorMessage(error));
    }
  }

  Future<void> _createForwarding() async {
    final aliasId = _aliasId;
    final destination = _forwardingDestination.text.trim().toLowerCase();
    if (aliasId == null || destination.isEmpty) return;
    setState(() => _forwardingSaving = true);
    try {
      await ref
          .read(wattEngineClientProvider)
          .createMailForwarding(
            mailboxId: widget.mailbox.id,
            aliasId: aliasId,
            destination: destination,
          );
      _forwardingDestination.clear();
      showSnackBar('forwardingCreated'.tr());
      _reload();
    } catch (error) {
      showSnackBar(wattApiErrorMessage(error));
    } finally {
      if (mounted) setState(() => _forwardingSaving = false);
    }
  }

  Future<void> _deleteForwarding(MailForwarding forwarding) async {
    final confirmed = await showConfirmAlert(
      'removeForwardingConfirm'.tr(
        namedArgs: {'destination': forwarding.destination},
      ),
      'removeForwarding'.tr(),
      icon: Symbols.delete,
      isDanger: true,
      confirmLabel: 'remove'.tr(),
    );
    if (!confirmed) return;
    try {
      await ref
          .read(wattEngineClientProvider)
          .deleteMailForwarding(widget.mailbox.id, forwarding.id);
      showSnackBar('forwardingRemoved'.tr());
      _reload();
    } catch (error) {
      showSnackBar(wattApiErrorMessage(error));
    }
  }

  @override
  Widget build(BuildContext context) {
    return SheetScaffold(
      titleText: widget.mailbox.fullAddress(widget.mailHost),
      heightFactor: 0.9,
      child: FutureBuilder<_RoutingData>(
        future: _data,
        builder: (context, snapshot) {
          if (snapshot.connectionState != ConnectionState.done) {
            return const PageLoading();
          }
          if (snapshot.hasError) {
            return PageError(
              message: 'workspaceMailboxDetailsLoadError'.tr(),
              onRetry: () => setState(() => _data = _load()),
            );
          }
          final data = snapshot.data!;
          return ListView(
            padding: const EdgeInsets.fromLTRB(20, 8, 20, 24),
            children: [
              _sheetSection('aliases', _aliasesBlock(data)),
              const SizedBox(height: 20),
              _sheetSection('forwarding', _forwardingBlock(data)),
              const SizedBox(height: 20),
              _sheetSection(
                'mailStorageQuota',
                _UsageMeter(
                  label: 'mailStorageQuota'.tr(),
                  used: data.quota.usedBytes,
                  limit: data.quota.limitBytes,
                  remaining: data.quota.remainingBytes,
                  isBytes: true,
                ),
              ),
              const SizedBox(height: 20),
              _sheetSection('workspaceSendUsage', _sendUsageBlock(data)),
            ],
          );
        },
      ),
    );
  }

  Widget _sheetSection(String titleKey, Widget child) {
    final text = Theme.of(context).textTheme;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(
          titleKey.tr(),
          style: text.titleMedium?.copyWith(fontWeight: FontWeight.w700),
        ),
        const SizedBox(height: 8),
        child,
      ],
    );
  }

  Widget _aliasesBlock(_RoutingData data) {
    final scheme = Theme.of(context).colorScheme;
    final text = Theme.of(context).textTheme;
    final verifiedDomains = widget.domains
        .where((domain) => domain.isReady)
        .toList(growable: false);
    final selectedDomainId =
        verifiedDomains.any((domain) => domain.id == _customDomainId)
        ? _customDomainId
        : null;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        if (verifiedDomains.isEmpty)
          Text(
            'noVerifiedDomains'.tr(),
            style: text.bodySmall?.copyWith(color: scheme.onSurfaceVariant),
          )
        else ...[
          DropdownButtonFormField<String>(
            initialValue: selectedDomainId,
            isExpanded: true,
            decoration: InputDecoration(
              isDense: true,
              labelText: 'customDomain'.tr(),
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(8),
              ),
            ),
            items: [
              for (final domain in verifiedDomains)
                DropdownMenuItem(value: domain.id, child: Text(domain.domain)),
            ],
            onChanged: (value) => setState(() => _customDomainId = value),
          ),
          const SizedBox(height: 10),
          TextField(
            controller: _aliasLocalPart,
            keyboardType: TextInputType.emailAddress,
            decoration: InputDecoration(
              labelText: 'aliasLocalPart'.tr(),
              hintText: 'aliasLocalPartHint'.tr(),
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(8),
              ),
            ),
          ),
          const SizedBox(height: 10),
          TextField(
            controller: _aliasName,
            decoration: InputDecoration(
              labelText: 'name'.tr(),
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(8),
              ),
            ),
          ),
          const SizedBox(height: 10),
          Align(
            alignment: Alignment.centerLeft,
            child: FilledButton.tonalIcon(
              onPressed: (_aliasSaving || selectedDomainId == null)
                  ? null
                  : _createAlias,
              icon: _aliasSaving
                  ? const SizedBox(
                      width: 16,
                      height: 16,
                      child: CircularProgressIndicator(strokeWidth: 2),
                    )
                  : const Icon(Symbols.add),
              label: Text('addAlias'.tr()),
            ),
          ),
        ],
        const SizedBox(height: 10),
        if (data.aliases.isEmpty)
          _InlineEmpty(icon: Symbols.alternate_email, message: 'noAliases'.tr())
        else
          for (final alias in data.aliases)
            _AliasRow(alias: alias, onDelete: () => _deleteAlias(alias)),
      ],
    );
  }

  Widget _forwardingBlock(_RoutingData data) {
    final scheme = Theme.of(context).colorScheme;
    final text = Theme.of(context).textTheme;
    final selectedAliasId =
        data.aliases.any((alias) => alias.id == _aliasId) ? _aliasId : null;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        if (data.aliases.isEmpty)
          Text(
            'workspaceForwardingAliasRequired'.tr(),
            style: text.bodySmall?.copyWith(color: scheme.onSurfaceVariant),
          )
        else ...[
          DropdownButtonFormField<String>(
            initialValue: selectedAliasId,
            isExpanded: true,
            decoration: InputDecoration(
              isDense: true,
              labelText: 'alias'.tr(),
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(8),
              ),
            ),
            items: [
              for (final alias in data.aliases)
                DropdownMenuItem(value: alias.id, child: Text(alias.address)),
            ],
            onChanged: (value) => setState(() => _aliasId = value),
          ),
          const SizedBox(height: 10),
          TextField(
            controller: _forwardingDestination,
            keyboardType: TextInputType.emailAddress,
            decoration: InputDecoration(
              labelText: 'forwardTo'.tr(),
              hintText: 'forwardToHint'.tr(),
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(8),
              ),
            ),
          ),
          const SizedBox(height: 10),
          Align(
            alignment: Alignment.centerLeft,
            child: FilledButton.tonalIcon(
              onPressed: (_forwardingSaving || selectedAliasId == null)
                  ? null
                  : _createForwarding,
              icon: _forwardingSaving
                  ? const SizedBox(
                      width: 16,
                      height: 16,
                      child: CircularProgressIndicator(strokeWidth: 2),
                    )
                  : const Icon(Symbols.add),
              label: Text('addForwarding'.tr()),
            ),
          ),
        ],
        const SizedBox(height: 10),
        if (data.forwardings.isEmpty)
          _InlineEmpty(icon: Symbols.forward_to_inbox, message: 'noForwarding'.tr())
        else
          for (final forwarding in data.forwardings)
            _ForwardingRow(
              forwarding: forwarding,
              alias: _aliasById(data.aliases, forwarding.aliasId),
              onDelete: () => _deleteForwarding(forwarding),
            ),
      ],
    );
  }

  Widget _sendUsageBlock(_RoutingData data) => Column(
    crossAxisAlignment: CrossAxisAlignment.stretch,
    children: [
      _UsageMeter(
        label: 'workspaceDaily'.tr(),
        used: data.sendUsage.daily.used,
        limit: data.sendUsage.daily.limit,
        remaining: data.sendUsage.daily.remaining,
      ),
      const SizedBox(height: 16),
      _UsageMeter(
        label: 'workspaceMonthly'.tr(),
        used: data.sendUsage.monthly.used,
        limit: data.sendUsage.monthly.limit,
        remaining: data.sendUsage.monthly.remaining,
      ),
    ],
  );
}

